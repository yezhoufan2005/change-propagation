"""Enumerate and classify the files under one or more roots.

Git repositories (a root, or any directory below it that has .git) are listed with
`git ls-files --cached --others --exclude-standard`, so .gitignore is respected; other
directories are walked. Vendored, built and binary files are skipped, and so are files that
may hold secrets (.env, keys), which are never read.
"""
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys

SKIP_DIRS = {".git", "node_modules", "vendor", "dist", "build", ".change-propagation", ".next",
             ".nuxt", ".output", "coverage", "__pycache__", ".venv", "venv", ".idea", ".vscode"}
SECRET_GLOBS = (".env", ".env.*", "*.pem", "*.key", "*.p12", "*.pfx", "id_rsa*", "*.keystore")
MAX_BYTES = 1_000_000
FRONTEND_EXT = {".vue", ".tsx", ".jsx", ".css", ".scss", ".sass", ".less", ".html", ".svelte"}
SCRIPT_EXT = {".ts", ".js", ".mjs", ".cjs", ".mts", ".cts"}
BACKEND_EXT = {".go", ".py", ".java", ".kt", ".rs", ".rb", ".php", ".cs"}
CONFIG_EXT = {".yml", ".yaml", ".toml", ".ini", ".conf", ".properties", ".json", ".xml"}
DOC_EXT = {".md", ".mdx", ".rst", ".txt", ".adoc"}
TEXT_EXT = FRONTEND_EXT | SCRIPT_EXT | BACKEND_EXT | CONFIG_EXT | DOC_EXT | {
    ".sql", ".sh", ".proto", ".graphql", ".tmpl", ".hbs", ".ejs", ".env.example"}
LOCKFILES = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "go.sum", "poetry.lock", "uv.lock",
             "Cargo.lock", "composer.lock"}
TEST_RE = re.compile(r"(_test\.go|_test\.py|\.(test|spec)\.[cm]?[jt]sx?)$|(^|/)(tests?|__tests__|e2e|testdata)/")
LOCALE_RE = re.compile(r"(^|/)(locales?|i18n|lang|langs|translations|messages)/", re.I)
DOCS_DIR_RE = re.compile(r"(^|/)(docs?|swagger|api-docs|openapi)/", re.I)
GENERATED_RE = re.compile(r"Code generated .* DO NOT EDIT|@generated|auto-generated|autogenerated", re.I)
BACKEND_DEPS = ("express", "koa", "fastify", "@nestjs/core", "@hapi/hapi", "hono", "egg")


def is_secret(name):
    return any(fnmatch.fnmatch(name, g) for g in SECRET_GLOBS) and not name.endswith(".example")


_GIT = []


def _git_candidates():
    """Git executables to try. On macOS /usr/bin/git is an xcrun shim: inside a sandbox that hides
    the real binary it fails, and outside one it may ask the user to install the developer tools.
    So it is never run; the binary of the selected developer directory is run instead."""
    found = shutil.which("git")
    if sys.platform != "darwin":
        return [found] if found else []
    out = [found] if found and os.path.realpath(found) != "/usr/bin/git" else []
    devs = [os.environ.get("DEVELOPER_DIR", "")]
    if os.path.islink("/var/db/xcode_select_link"):
        devs.append(os.path.realpath("/var/db/xcode_select_link"))
    devs += ["/Library/Developer/CommandLineTools", "/Applications/Xcode.app/Contents/Developer"]
    out += [os.path.join(d, "usr", "bin", "git") for d in devs if d]
    return list(dict.fromkeys(p for p in out if os.path.isfile(p)))


def git_exe():
    """A git executable that runs here, or None (then cplib/gitread reads .git directly)."""
    if not _GIT:
        found = None
        for exe in _git_candidates():
            try:
                r = subprocess.run([exe, "--version"], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=10)
            except (OSError, subprocess.SubprocessError):
                continue
            if r.returncode == 0 and r.stdout.startswith(b"git version"):
                found = exe
                break
        _GIT.append(found)
    return _GIT[0]


def _git_files(repo):
    if git_exe() is None:
        return None
    try:
        out = subprocess.run(
            [git_exe(), "-C", repo, "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True, timeout=60).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    return [p for p in out.decode("utf-8", "replace").split("\0") if p]


def _walk(top):
    """Yield paths relative to `top`; nested git repositories are listed with git."""
    for dirpath, dirnames, filenames in os.walk(top):
        rel_dir = os.path.relpath(dirpath, top)
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        if dirpath != top and os.path.exists(os.path.join(dirpath, ".git")):
            files = _git_files(dirpath)
            if files is not None:
                dirnames[:] = []
                for f in files:
                    yield rel_dir + f
                continue
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            yield rel_dir + f


def list_files(root):
    """Paths relative to `root`, filtered to text files worth searching."""
    root = os.path.abspath(root)
    files = _git_files(root) if os.path.exists(os.path.join(root, ".git")) else None
    paths = files if files is not None else _walk(root)
    out = []
    for rel in paths:
        parts = rel.split("/")
        name = parts[-1]
        if any(p in SKIP_DIRS for p in parts[:-1]) or name in LOCKFILES or is_secret(name):
            continue
        ext = os.path.splitext(name)[1].lower()
        if ext not in TEXT_EXT or name.endswith((".min.js", ".min.css", ".map")):
            continue
        full = os.path.join(root, rel)
        try:
            if os.path.getsize(full) > MAX_BYTES or os.path.islink(full):
                continue
        except OSError:
            continue
        out.append(rel)
    return sorted(set(out))


def read_lines(path):
    try:
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return None
    if b"\0" in data[:4096]:
        return None
    return data.decode("utf-8", "replace").split("\n")


def is_generated(lines):
    return any(GENERATED_RE.search(l) for l in lines[:5])


class StackGuesser:
    """Frontend or backend for script files, from the nearest package.json."""

    def __init__(self, root):
        self.root = root
        self.cache = {}

    def _package_kind(self, rel_dir):
        if rel_dir in self.cache:
            return self.cache[rel_dir]
        kind = None
        pkg = os.path.join(self.root, rel_dir, "package.json")
        if os.path.isfile(pkg):
            try:
                with open(pkg, encoding="utf-8") as fh:
                    data = json.load(fh)
                deps = {}
                for key in ("dependencies", "devDependencies", "peerDependencies"):
                    deps.update(data.get(key) or {})
                kind = "backend" if any(d in deps for d in BACKEND_DEPS) else "frontend"
            except (OSError, ValueError, AttributeError):
                kind = None
        if kind is None and rel_dir:
            kind = self._package_kind(os.path.dirname(rel_dir))
        self.cache[rel_dir] = kind
        return kind

    def stack(self, rel):
        ext = os.path.splitext(rel)[1].lower()
        if ext in FRONTEND_EXT:
            return "frontend"
        if ext in BACKEND_EXT:
            return "backend"
        if ext in SCRIPT_EXT:
            if re.search(r"(^|/)(server|backend|api-server)/", rel):
                return "backend"
            return self._package_kind(os.path.dirname(rel)) or "frontend"
        return None


def layer(rel, stack):
    """One of frontend, backend, locale, test, docs, config, sql, other."""
    ext = os.path.splitext(rel)[1].lower()
    if TEST_RE.search(rel):
        return "test"
    if LOCALE_RE.search(rel) and ext in CONFIG_EXT | SCRIPT_EXT:
        return "locale"
    if ext in DOC_EXT or (DOCS_DIR_RE.search(rel) and ext in CONFIG_EXT | {".go"}):
        return "docs"
    if ext == ".sql":
        return "sql"
    if stack:
        return stack
    if ext in CONFIG_EXT:
        return "config"
    return "other"
