    def run_cp(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            cp.main(list(argv))
        return out.getvalue()

    def ledger(self):
        return json.loads((self.repo.root / ".change-propagation" / "ledger.json").read_text(encoding="utf-8"))

    def test_seed_scan_mark_verify(self):
        self.run_cp("seed", "--change", "最短 6 改 8", "--value", "6", "--near", "password,密码",
                    "--file", "web/src/Register.vue")
        out = self.run_cp("scan")
        self.assertIn("rule", out)
        self.assertEqual((self.repo.root / ".change-propagation" / ".gitignore").read_text(), "*\n")
        items = {(i["path"], i["line"]): i["id"] for i in self.ledger()["items"]}
        check = items[("web/src/Register.vue", 7)]
        server = items[("server/model/users.go", 2)]
        # IDs are stable across rescans
        self.run_cp("scan")
        self.assertEqual({(i["path"], i["line"]): i["id"] for i in self.ledger()["items"]}, items)
        self.run_cp("mark", server, "--tier", "coupled", "--status", "asked")
        with self.assertRaises(SystemExit):
            self.run_cp("mark", server, "--status", "edited")
        p = self.repo.root / "web/src/Register.vue"
        p.write_text(p.read_text(encoding="utf-8").replace("< 6", "< 8"), encoding="utf-8")
        self.run_cp("mark", check, "--tier", "direct", "--status", "edited")
        self.run_cp("mark", "rest", "--tier", "review", "--status", "listed")
        out = self.run_cp("verify")
        self.assertIn("等你确认", out)          # the coupled item is still asked
        self.assertNotIn("新出现的命中", out)    # the edited line is not reported as new
        self.run_cp("mark", server, "--status", "declined", "--note", "用户不同意")
        self.assertIn("复查通过", self.run_cp("verify"))

