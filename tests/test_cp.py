class ResidueTest(unittest.TestCase):
    """A page and its copy that always change together; the copy's line drifted (`|| '--'`)."""
    OLD = "  hint.value = $t('form.as') + '：' + item.placeholder\n"
    PAGE = "<script setup>\n" + OLD + "const a = 1\n" + OLD + "</script>\n"
    COPY = "<script setup>\n  hint.value = $t('form.as') + '：' + item.placeholder || '--'\n</script>\n"

    def setUp(self):
        self.repo = Repo({"web/package.json": "{}", "web/src/page.vue": self.PAGE, "web/src/copy.vue": self.COPY,
                          "web/src/other.vue": "<script setup>\nconst b = 2\n</script>\n"})
        self.root = str(self.repo.root)
        git = ["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(git[:3] + ["init", "-q"], check=True)
        for i in range(3):
            for name in ("page.vue", "copy.vue"):
                p = self.repo.root / "web/src" / name
                p.write_text(p.read_text() + "<!-- %d -->\n" % i)
            subprocess.run(git + ["add", "-A"], check=True)
            subprocess.run(git + ["commit", "-qm", "c%d" % i], check=True)

    def tearDown(self):
        self.repo.close()

    def edit(self, name, old, new, count=1):
        p = self.repo.root / "web/src" / name
        p.write_text(p.read_text().replace(old, new, count))

    def found(self):
        files, _ = channels.load_corpus([self.root], self.root)
        return sorted((h["path"], h["line"]) for h in history.residue(files, [self.root], self.root))

    def test_finds_second_copy_in_file_and_drifted_copy_in_partner(self):
        self.edit("page.vue", "+ item.placeholder\n", "+ (item.placeholder || '')\n")
        self.assertEqual(self.found(), [("web/src/copy.vue", 2), ("web/src/page.vue", 4)])

    def test_copy_fixed_the_same_way_is_not_reported(self):
        self.edit("page.vue", "$t('form.as') + '：' + item.placeholder\n",
                  "item.placeholder ? $t('form.as') + '：' + item.placeholder : ''\n", 2)
        self.edit("copy.vue", "$t('form.as') + '：' + item.placeholder || '--'",
                  "item.placeholder ? $t('form.as') + '：' + item.placeholder : '--'")
        # copy.vue's own diff is an edit too; its removed line is fixed everywhere
        self.assertEqual(self.found(), [])

    def test_diff_hunks_keeps_removed_line_that_starts_with_dashes(self):
        (self.repo.root / "web/q.sql").write_text("-- keep in sync\nselect 1;\n")
        git = ["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(git + ["add", "-A"], check=True)
        subprocess.run(git + ["commit", "-qm", "sql"], check=True)
        (self.repo.root / "web/q.sql").write_text("select 1;\n")
        self.assertEqual(history.diff_hunks(self.root), [("web/q.sql", ["-- keep in sync"], [])])

    def test_verify_skips_changes_from_before_the_task(self):
        cwd = os.getcwd()
        os.chdir(self.root)
        try:
            # Someone's uncommitted work in copy.vue removed a line that page.vue still has.
            self.edit("copy.vue", "  hint.value = $t('form.as') + '：' + item.placeholder || '--'\n", "")
            with contextlib.redirect_stdout(io.StringIO()):
                cp.main(["seed", "--new", "--scan", "--change", "x", "--name", "other"])
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                cp.main(["verify"])
            self.assertNotIn("page.vue", out.getvalue())
        finally:
            os.chdir(cwd)

    def test_repos_below_a_workspace_root(self):
        with tempfile.TemporaryDirectory() as d:
            for name in ("web", "server"):
                subprocess.run(["git", "init", "-q", os.path.join(d, name)], check=True)
            self.assertEqual(sorted(os.path.basename(r) for r in history.repos([d])), ["server", "web"])

    def test_repos_of_a_workspace_inside_another_repository(self):
        # The eval sandbox keeps a repository in the home directory, above the workspace; the
        # workspace counts as one even when that repository has files in it.
        with tempfile.TemporaryDirectory() as d:
            d = os.path.realpath(d)
            ws = os.path.join(d, "ws")
            for top in (d, os.path.join(ws, "web"), os.path.join(ws, "server")):
                subprocess.run(["git", "init", "-q", top], check=True)
            pathlib.Path(ws, "README.md").write_text("workspace\n")
            git = ["git", "-C", d, "-c", "user.name=t", "-c", "user.email=t@t"]
            subprocess.run(git + ["add", "ws/README.md"], check=True)
            subprocess.run(git + ["commit", "-qm", "a"], check=True)
            os.makedirs(os.path.join(ws, "web", "src"))
            self.assertEqual(sorted(os.path.basename(r) for r in history.repos([ws])), ["server", "web"])
            self.assertEqual(history.repos([d]), [d])
            self.assertEqual(history.repos([os.path.join(ws, "web", "src")]), [os.path.join(ws, "web")])


class GitExeTest(unittest.TestCase):
    def test_skips_git_on_path_that_fails(self):
        # The macOS /usr/bin/git shim fails inside a sandbox that hides the user temp directory.
        with tempfile.TemporaryDirectory() as d:
            fake = os.path.join(d, "git")
            with open(fake, "w") as fh:
                fh.write("#!/bin/sh\necho \"xcode-select: Failed to locate 'git'\" >&2\nexit 1\n")
            os.chmod(fake, 0o755)
            old_path, old_cache = os.environ["PATH"], list(channels.walk._GIT)
            os.environ["PATH"] = d + os.pathsep + old_path
            channels.walk._GIT.clear()
            try:
                self.assertNotEqual(channels.walk.git_exe(), fake)
            finally:
                os.environ["PATH"] = old_path
                channels.walk._GIT[:] = old_cache


class GitReadTest(unittest.TestCase):
    """cplib/gitread must give what the git binary gives: packed objects with offset and reference
    deltas, loose objects, a merge, a deleted file, a non-ASCII name, working-tree edits."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = os.path.realpath(self.tmp.name)
        self.git("init", "-q", "-b", "main", ".")
        body = "".join("line %d of a long enough file\n" % i for i in range(60))
        self.write("src/a.ts", body)
        self.write("src/b.ts", body.replace("line", "row"))
        self.write("docs/说明.md", "# 说明\n" + body)
        self.write("gone.txt", "to be deleted\n")
        self.commit("c0")
        for i in range(1, 4):
            self.write("src/a.ts", body.replace("line %d " % i, "LINE %d " % i))
            self.write("src/b.ts", body.replace("row", "ROW", i))
            self.commit("c%d" % i)
        self.git("checkout", "-q", "-b", "side")
        self.write("src/c.ts", "side branch\n" + body)
        self.write("src/a.ts", body + "side\n")
        self.commit("side")
        self.git("checkout", "-q", "main")
        self.write("docs/说明.md", "# 说明 v2\n" + body)
        os.remove(os.path.join(self.root, "gone.txt"))
        self.commit("main after side")
        self.git("merge", "-q", "--no-edit", "side")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        return subprocess.run(["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t",
                               "-c", "core.quotePath=false"] + list(args),
                              stdout=subprocess.PIPE, check=True).stdout.decode("utf-8")

    def write(self, rel, text):
        p = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(text)

    def commit(self, msg):
        self.git("add", "-A")
        self.git("commit", "-qm", msg)

    def check_against_git(self):
        top, repo = gitread.open_repo(self.root)
        tree = {}
        for line in filter(None, self.git("ls-tree", "-r", "-z", "HEAD").split("\0")):
            meta, path = line.split("\t", 1)
            tree[path] = meta.split()[2]
        self.assertEqual({p: i for p, (_, i) in gitread.head_files(repo).items()}, tree)
        for ident in tree.values():
            want = subprocess.run(["git", "-C", self.root, "cat-file", "blob", ident], stdout=subprocess.PIPE).stdout
            self.assertEqual(repo.read(ident)[1], want)
        for path in ("src/a.ts", "src/b.ts", "docs/说明.md", "src/c.ts", "gone.txt"):
            out = self.git("log", "--no-merges", "--no-renames", "--full-diff", "--name-only",
                           "--format=tformat:@@", "--", path)
            want = [set(filter(None, c.split("\n"))) for c in out.split("@@")[1:]]
            self.assertEqual(gitread.log(top, repo, [path], 100, 30), want, path)

    def test_loose_objects(self):
        self.check_against_git()

    def test_packed_with_offset_deltas(self):
        self.git("repack", "-adfq", "--window=50")
        self.assertTrue(any(n.endswith(".pack") for n in os.listdir(os.path.join(self.root, ".git/objects/pack"))))
        self.check_against_git()

    def test_packed_with_reference_deltas(self):
        self.git("-c", "repack.useDeltaBaseOffset=false", "repack", "-adfq", "--window=50")
        self.check_against_git()

    def test_working_tree_against_head(self):
        self.git("repack", "-adq")
        self.write("src/a.ts", "added first\n" + pathlib.Path(self.root, "src/b.ts").read_text(encoding="utf-8"))
        os.remove(os.path.join(self.root, "src/c.ts"))
        self.write("new.txt", "untracked\n")
        top, repo = gitread.open_repo(self.root)
        gitread.reset()
        self.assertEqual(gitread.changed_files(top, repo),
                         sorted(filter(None, self.git("diff", "--name-only", "HEAD").split("\n"))))
        removed = collections.Counter()
        added = collections.Counter()
        for path, rem, add in gitread.diff_hunks(top, repo):
            removed.update((path, l) for l in rem)
            added.update((path, l) for l in add)
        want_rem, want_add = collections.Counter(), collections.Counter()
        for path, rem, add in history.diff_hunks(self.root):
            want_rem.update((path, l) for l in rem)
            want_add.update((path, l) for l in add)
        self.assertEqual((removed, added), (want_rem, want_add))
        self.assertEqual(gitread.untracked(top, repo, channels.walk.list_files(top)), ["new.txt"])


